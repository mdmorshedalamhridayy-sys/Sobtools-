import React, { useState, useRef, useEffect } from 'react';
import { Upload, Download, Printer, UserCheck, Sliders } from 'lucide-react';
import { downloadBlob, readFileAsDataURL } from '../../utils/fileHelpers';
import { useLanguage } from '../../context/LanguageContext';

export const PassportPhotoMaker: React.FC = () => {
  const { language, t } = useLanguage();
  const [photoUrl, setPhotoUrl] = useState<string | null>(null);
  const [photoType, setPhotoType] = useState<'bd' | 'us' | 'stamp'>('bd');
  const [copies, setCopies] = useState<number>(8);
  const [sheetBg, setSheetBg] = useState<'white' | 'blue' | 'grey'>('white');
  const [hasBorder, setHasBorder] = useState<boolean>(true);
  const [sheetBlob, setSheetBlob] = useState<Blob | null>(null);
  const [sheetUrl, setSheetUrl] = useState<string | null>(null);
  
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const fileInputRef = useRef<HTMLInputElement>(null);

  const handleFileChange = async (e: React.ChangeEvent<HTMLInputElement>) => {
    if (e.target.files && e.target.files[0]) {
      const url = await readFileAsDataURL(e.target.files[0]);
      setPhotoUrl(url);
    }
  };

  useEffect(() => {
    if (!photoUrl) return;

    const img = new Image();
    img.src = photoUrl;
    img.onload = () => {
      const canvas = canvasRef.current;
      if (!canvas) return;
      const ctx = canvas.getContext('2d');
      if (!ctx) return;

      // 4x6 inch standard photographic paper at 300 DPI: 1200 x 1800 px (Landscape: 1800 x 1200)
      canvas.width = 1800;
      canvas.height = 1200;

      // Fill canvas background
      ctx.fillStyle = '#FFFFFF';
      ctx.fillRect(0, 0, canvas.width, canvas.height);

      // Photo size dimensions on sheet
      let photoW = 350;
      let photoH = 450;
      if (photoType === 'us') {
        photoW = 450;
        photoH = 450;
      } else if (photoType === 'stamp') {
        photoW = 240;
        photoH = 300;
      }

      // Calculate grid arrangement (columns and rows) based on copies
      let cols = 4;
      let rows = 2;
      if (copies === 4) {
        cols = 2;
        rows = 2;
      } else if (copies === 6) {
        cols = 3;
        rows = 2;
      } else if (copies === 8) {
        cols = 4;
        rows = 2;
      } else if (copies === 12) {
        cols = 4;
        rows = 3;
      } else if (copies === 16) {
        cols = 4;
        rows = 4;
        photoW = Math.round(photoW * 0.7);
        photoH = Math.round(photoH * 0.7);
      }

      const totalGridW = cols * photoW;
      const totalGridH = rows * photoH;
      const startX = Math.max(20, Math.floor((canvas.width - totalGridW) / (cols + 1)));
      const startY = Math.max(20, Math.floor((canvas.height - totalGridH) / (rows + 1)));

      let count = 0;
      for (let r = 0; r < rows; r++) {
        for (let c = 0; c < cols; c++) {
          if (count >= copies) break;
          const x = startX + c * (photoW + startX);
          const y = startY + r * (photoH + startY);

          // Fill photo background color
          if (sheetBg === 'blue') {
            ctx.fillStyle = '#CBE2FB';
            ctx.fillRect(x, y, photoW, photoH);
          } else if (sheetBg === 'grey') {
            ctx.fillStyle = '#E5E7EB';
            ctx.fillRect(x, y, photoW, photoH);
          }

          // Draw image centered in photo box
          ctx.drawImage(img, x, y, photoW, photoH);

          // Draw thin cutting guide border
          if (hasBorder) {
            ctx.strokeStyle = '#94A3B8';
            ctx.lineWidth = 1;
            ctx.strokeRect(x, y, photoW, photoH);
          }

          count++;
        }
      }

      // Header stamp text on bottom margin
      ctx.fillStyle = '#94A3B8';
      ctx.font = '20px sans-serif';
      ctx.textAlign = 'center';
      ctx.fillText('Generated by SobTools (sobtools.com) — 4x6" Printable Photo Sheet', canvas.width / 2, canvas.height - 25);

      canvas.toBlob((blob) => {
        if (!blob) return;
        setSheetBlob(blob);
        if (sheetUrl) URL.revokeObjectURL(sheetUrl);
        setSheetUrl(URL.createObjectURL(blob));
      }, 'image/png');
    };
  }, [photoUrl, photoType, copies, sheetBg, hasBorder]);

  const handleDownload = () => {
    if (!sheetBlob) return;
    downloadBlob(sheetBlob, `passport-photos-4x6-sheet.png`);
  };

  const handlePrint = () => {
    if (!sheetUrl) return;
    const printWindow = window.open(sheetUrl, '_blank');
    if (printWindow) {
      printWindow.addEventListener('load', () => {
        printWindow.print();
      });
    }
  };

  return (
    <div className="space-y-6">
      {!photoUrl ? (
        <div
          onClick={() => fileInputRef.current?.click()}
          className="border-2 border-dashed border-slate-700 hover:border-indigo-500 rounded-2xl p-10 text-center cursor-pointer bg-slate-950/40 hover:bg-slate-900/60 transition-all group"
        >
          <input
            ref={fileInputRef}
            type="file"
            accept="image/*"
            className="hidden"
            onChange={handleFileChange}
          />
          <div className="w-16 h-16 rounded-2xl bg-indigo-500/10 border border-indigo-500/20 text-indigo-400 flex items-center justify-center mx-auto mb-4 group-hover:scale-110 transition-transform">
            <UserCheck className="w-8 h-8" />
          </div>
          <h3 className="text-base font-semibold text-slate-200">
            {language === 'bn' ? 'আপনার ছবিটি আপলোড করুন' : 'Upload your portrait photo'}
          </h3>
          <p className="text-xs text-slate-400 mt-1.5">
            {language === 'bn'
              ? 'বাংলাদেশ পাসপোর্ট (৪৫x৩৫ মিমি), ইউএস ভিসা বা স্ট্যাম্প সাইজের শিট বানান।'
              : 'Arrange 4, 8, or 12 photos on a 4x6" print sheet with cut guidelines.'}
          </p>
          <button
            type="button"
            className="mt-5 px-5 py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white font-medium text-xs shadow-lg shadow-indigo-600/25 transition-all"
          >
            {t('browseFiles')}
          </button>
        </div>
      ) : (
        <div className="space-y-6">
          {/* Controls */}
          <div className="p-4 rounded-xl bg-slate-950/60 border border-slate-800 grid grid-cols-1 sm:grid-cols-4 gap-4 items-center">
            <div>
              <label className="text-xs font-semibold text-slate-300 block mb-1">
                {language === 'bn' ? 'ছবির সাইজ' : 'Photo Specification'}
              </label>
              <select
                value={photoType}
                onChange={(e) => setPhotoType(e.target.value as any)}
                className="w-full px-3 py-1.5 rounded-xl bg-slate-900 border border-slate-700 text-xs text-slate-200"
              >
                <option value="bd">বাংলাদেশ পাসপোর্ট (45×35 mm)</option>
                <option value="us">US Visa / 2×2 Inch</option>
                <option value="stamp">স্ট্যাম্প সাইজ (25×20 mm)</option>
              </select>
            </div>

            <div>
              <label className="text-xs font-semibold text-slate-300 block mb-1">
                {language === 'bn' ? 'ছবির সংখ্যা (কপি)' : 'Copies Count'}
              </label>
              <select
                value={copies}
                onChange={(e) => setCopies(Number(e.target.value))}
                className="w-full px-3 py-1.5 rounded-xl bg-slate-900 border border-slate-700 text-xs text-slate-200"
              >
                <option value={4}>৪টি ছবি (4 Copies)</option>
                <option value={6}>৬টি ছবি (6 Copies)</option>
                <option value={8}>৮টি ছবি (8 Copies - Recommended)</option>
                <option value={12}>১২টি ছবি (12 Copies)</option>
                <option value={16}>১৬টি ছবি (16 Copies)</option>
              </select>
            </div>

            <div className="flex items-center gap-2 pt-4">
              <label className="flex items-center gap-2 text-xs text-slate-300 cursor-pointer">
                <input
                  type="checkbox"
                  checked={hasBorder}
                  onChange={(e) => setHasBorder(e.target.checked)}
                  className="rounded accent-indigo-500"
                />
                <span>{language === 'bn' ? 'কাটার বর্ডার দিন' : 'Cutting Borders'}</span>
              </label>
            </div>

            <div className="flex items-center justify-end gap-2 pt-2">
              <button
                type="button"
                onClick={() => setPhotoUrl(null)}
                className="px-3 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs font-medium"
              >
                {t('reset')}
              </button>
              <button
                type="button"
                onClick={handleDownload}
                disabled={!sheetBlob}
                className="px-4 py-2 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-semibold flex items-center gap-1.5 shadow-lg shadow-indigo-600/25"
              >
                <Download className="w-4 h-4" />
                {t('download')}
              </button>
            </div>
          </div>

          {/* Printable Sheet View */}
          <div className="p-4 rounded-xl bg-slate-950/40 border border-slate-800 text-center">
            <div className="flex items-center justify-between mb-3 text-xs text-slate-400">
              <span className="font-semibold text-slate-200">
                {language === 'bn' ? '৪x৬ ইঞ্চি প্রিন্ট শিট প্রিভিউ:' : '4x6" Printable Sheet Preview:'}
              </span>
              <span className="text-[11px] font-mono text-emerald-400">
                1800 × 1200 px (300 DPI Studio Quality)
              </span>
            </div>
            <div className="max-h-[500px] overflow-auto rounded-lg bg-slate-900/60 p-4 flex justify-center border border-slate-800">
              <canvas
                ref={canvasRef}
                className="max-w-full max-h-[460px] object-contain shadow-2xl rounded border border-slate-700"
              />
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
